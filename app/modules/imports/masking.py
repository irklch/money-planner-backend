"""Маскирование персональных данных перед отправкой в ИИ.

Удаляются/маскируются: номера карт и счетов, телефоны, email, ФИО третьих лиц.
Применяется ко всем строкам, уходящим в LLM. Исходный comment пользователю не меняется.
"""

import re

_RULES: list[tuple[re.Pattern, str]] = [
    # Счёт: 20 цифр (возможны пробелы)
    (re.compile(r"(?<!\d)(?:\d[ ]?){19}\d(?!\d)"), "[СЧЁТ]"),
    # Карта: 13–19 цифр подряд или группами
    (re.compile(r"(?<!\d)(?:\d[ -]?){12,18}\d(?!\d)"), "[КАРТА]"),
    # Карта с маской после BIN: 220015******1234, 427601++++++5678
    (re.compile(r"(?<!\d)\d{4,6}[*+•xX]{2,}\d{2,4}(?!\d)"), "[КАРТА]"),
    # Маскированные карты/счета банка: 4276 **** 1234, *1234, ••1234, XX1234
    (re.compile(r"(?:\d{4}[ ]?)?(?:[*•xX]{2,}[ ]?){1,3}\d{2,4}"), "[КАРТА]"),
    (re.compile(r"(?<![\w*])[*•]\d{4}(?!\d)"), "[КАРТА]"),
    # Email
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"), "[EMAIL]"),
    # Телефон РФ: +7 / 8, различные разделители
    (re.compile(r"(?<!\d)(?:\+7|8|7)[\s(.-]*\d{3}[\s).-]*\d{3}[\s.-]*\d{2}[\s.-]*\d{2}(?!\d)"), "[ТЕЛЕФОН]"),
    # ФИО с отчеством: Иванов Иван Иванович / ИВАН ИВАНОВИЧ И.
    (re.compile(r"(?i)\b[а-яё]+\s+[а-яё]+\s+[а-яё]+(?:вич|вна|ична|ьич|инична)\b"), "[ФИО]"),
    (re.compile(r"(?i)\b[а-яё]+\s+[а-яё]+(?:вич|вна|ична|ьич|инична)(?:\s+[а-яё]\.)?"), "[ФИО]"),
    # Имя + инициал(ы): Иван И. / Иванов И.И. / И. Иванов
    (re.compile(r"\b[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.)?"), "[ФИО]"),
    (re.compile(r"\b[А-ЯЁ]{2,}\s+[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.)?"), "[ФИО]"),
    (re.compile(r"\b[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.\s?)?[А-ЯЁ][а-яё]+"), "[ФИО]"),
]

# Переводы физлицам: всё после ключевой фразы — получатель/отправитель.
_TRANSFER = re.compile(
    r"(?i)^(перевод[а-я]*|внутренний перевод|внутрибанковский перевод|входящий перевод|исходящий перевод)"
    r"(\s+(по номеру телефона|с карты|на карту|для|от|клиенту|через сбп|по сбп|сбп))*\b.*$"
)


# Альфа-Банк начинает описание с типа операции: «Категория: Перевод по СБП. Перевод …».
_CATEGORY_PREFIX = re.compile(r"(?i)^категория:[^.]*\.\s*")


def mask_pii(text: str | None) -> str:
    if not text:
        return ""
    s = " ".join(text.split())
    if m := _TRANSFER.match(_CATEGORY_PREFIX.sub("", s, count=1)):
        return f"{m.group(1)} [ПОЛУЧАТЕЛЬ]"
    for rx, repl in _RULES:
        s = rx.sub(repl, s)
    return s


_NOISE = re.compile(r"(?i)\b(оплата|покупка|списание|операция по карте|retail|rus|ru|moscow|москва)\b")
_DIGITS = re.compile(r"\d{3,}")
_PLACEHOLDER = re.compile(r"\[[А-ЯЁA-Z]+\]")


def merchant_key(masked: str) -> str:
    """Ключ группировки одинаковых мерчантов (детерминированная нормализация)."""
    s = _PLACEHOLDER.sub(" ", masked)
    s = _NOISE.sub(" ", s)
    s = _DIGITS.sub(" ", s)
    s = re.sub(r"[^\w\s.&'-]", " ", s)
    return " ".join(s.upper().split())[:80]
